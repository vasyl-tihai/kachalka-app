// i18n.js — переклади інтерфейсу.
// Ключ = український рядок (мова за замовчуванням). t() повертає переклад
// поточної мови, а якщо його немає — англійський, а якщо й того нема — сам ключ.

export const LANGS = [
  { id: 'uk', label: 'Українська' },
  { id: 'en', label: 'English' },
  { id: 'pl', label: 'Polski' },
  { id: 'de', label: 'Deutsch' },
  { id: 'es', label: 'Español' },
  { id: 'fr', label: 'Français' },
  { id: 'it', label: 'Italiano' },
];

let cur = 'uk';
export function setLang(l) {
  cur = LANGS.some((x) => x.id === l) ? l : 'uk';
}
export function getLang() {
  return cur;
}

/** Переклад рядка; vars — підстановки виду {name}. */
export function t(key, vars) {
  let s = cur === 'uk' ? key : (D[cur] && D[cur][key]) ?? (D.en && D.en[key]) ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}

/** Множина: plural(n, 'день', 'дні', 'днів') — форми передаються українською і перекладаються. */
export function plural(n, one, few, many) {
  const m10 = n % 10;
  const m100 = n % 100;
  let form = many;
  if (m10 === 1 && m100 !== 11) form = one;
  else if (m10 >= 2 && m10 <= 4 && (m100 < 10 || m100 >= 20)) form = few;
  return t(form);
}

