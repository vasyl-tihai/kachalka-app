// підбір за назвою (укр/англ) і типом ваги; порядок важливий
const RULES = [
  [/берпі|burpee/i, () => 'burpee'],
  [/станов|deadlift|румун/i, () => 'deadlift'],
  [/випад|lunge/i, () => 'lunge'],
  [/планк|plank/i, () => 'plank'],
  [/присід|squat/i, (e) => (e.weightType === 'bodyweight' || /легк/i.test(e.name) ? 'squat_bw' : 'squat')],
  [/підтяг|pull.?up|chin.?up/i, () => 'pullup'],
  [/жим.*(леж|bench)|bench/i, (e) => (e.weightType === 'dumbbell' || /гантел|dumbbell/i.test(e.name) ? 'bench_db' : 'bench_bb')],
  [/віджим|push.?up/i, () => 'pushup'],
  [/жим|press/i, () => 'ohp'],
  [/біцепс|згинан|curl/i, () => 'curl'],
  [/прес|скруч|crunch|abs/i, () => 'crunch'],
  [/тяга|row/i, (e) => (e.weightType === 'dumbbell' || /гантел|dumbbell/i.test(e.name) ? 'row_db' : 'row_bb')],
];

/** id інструкції для вправи або null (кардіо, розтяжка, власні вправи без збігу). */
export function guideFor(ex) {
  const name = String((ex && ex.name) || '');
  for (const [re, pick] of RULES) if (re.test(name)) return pick(ex || {});
  return null;
}
